/**
 * Generates packages/llm/src/common-words.generated.ts: the words that are frequent in ordinary READMEs, per language.
 *
 *   pnpm exec tsx scripts/gen-common-words.ts [corpus-dir] [--threshold 0.05]
 *
 * The corpus is a folder with one sub-folder per language (en, pt, es) of real README files (the benign base; the texts are NOT
 * committed, only the generated word list, which is not README text). A word is "common" in a language when it occurs in at least
 * THRESHOLD of the documents of that language (document frequency, not total count: one README that repeats a word 500 times does
 * not make it common). Words with a digit are never listed (an identifier or a canary is not a common word), and the lines the
 * keyword rules flag are removed before counting (an attack line in the corpus must not make its words "common").
 * See the header of the generated file for the numbers.
 */
import { flaggedSegments } from "@quizforge/core";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const args = process.argv.slice(2);
const flag = (name: string, def: string): string => {
  const i = args.indexOf(name);
  return i >= 0 ? args[i + 1]! : def;
};
const corpus = resolve(args.find((a, i) => !a.startsWith("--") && args[i - 1] !== "--threshold") ?? "/home/jhgcc1/qf-benign-wide");
const threshold = Number(flag("--threshold", "0.05"));
const LANGS = ["en", "pt", "es"] as const;
const TOKEN = /[\p{L}\p{N}]{3,}/gu;
const MAX_LEN = 24;

const lists: Record<string, string[]> = {};
const docCounts: Record<string, number> = {};
for (const lang of LANGS) {
  const files = readdirSync(join(corpus, lang)).filter((f) => f.endsWith(".md"));
  const df = new Map<string, number>();
  for (const f of files) {
    let text = readFileSync(join(corpus, lang, f), "utf8");
    for (const seg of flaggedSegments(text)) text = text.split(seg).join(" ");
    text = text.replace(/https?:\/\/\S+/g, " ").toLowerCase().normalize("NFKC");
    for (const w of new Set(text.match(TOKEN) ?? [])) df.set(w, (df.get(w) ?? 0) + 1);
  }
  docCounts[lang] = files.length;
  lists[lang] = [...df]
    .filter(([w, d]) => d / files.length >= threshold && !/\p{N}/u.test(w) && w.length <= MAX_LEN)
    .map(([w]) => w)
    .sort((a, b) => a.localeCompare(b));
}
const union = new Set(Object.values(lists).flat());

const wrap = (words: string[]): string => {
  const lines: string[] = [];
  let line = "";
  for (const w of words) {
    if (line.length + w.length + 1 > 140) {
      lines.push(line);
      line = "";
    }
    line += (line ? " " : "") + w;
  }
  if (line) lines.push(line);
  return lines.map((l) => `  ${l}`).join("\n");
};

const out = `// GENERATED by scripts/gen-common-words.ts. Do not edit by hand: change the script or the threshold and run it again.
//
// Words that occur in at least ${(threshold * 100).toFixed(0)}% of the READMEs of their language (document frequency), from a base of real READMEs
// (${LANGS.map((l) => `${docCounts[l]} ${l}`).join(", ")}; the texts are not committed, this list is not README text). Lines flagged by the keyword
// rules were removed before counting, and words with a digit or longer than ${MAX_LEN} letters are never listed.
// Sizes: ${LANGS.map((l) => `${l} ${lists[l]!.length}`).join(", ")}; union ${union.size}.
// Used by output-guard.ts: such a word can never be a "planted word" (an ordinary word of a quoted attack line, like "system").

export const COMMON_WORDS_THRESHOLD = ${threshold};

const COMMON_WORDS_TEXT: Record<"en" | "pt" | "es", string> = {
${LANGS.map((l) => `  ${l}: \`\n${wrap(lists[l]!)}\n  \``).join(",\n")},
};

export const COMMON_WORDS: ReadonlySet<string> = new Set(Object.values(COMMON_WORDS_TEXT).flatMap((t) => t.split(/\\s+/).filter(Boolean)));
`;
const target = join(dirname(fileURLToPath(import.meta.url)), "..", "packages", "llm", "src", "common-words.generated.ts");
writeFileSync(target, out);
console.log(`wrote ${target}: ${LANGS.map((l) => `${l} ${lists[l]!.length}`).join(", ")}, union ${union.size}, threshold ${threshold}`);
