/**
 * Step 1 of the public-dataset part: reads the public datasets (network), draws the seeded sample and writes the promptfoo tests.
 *
 *   tsx promptfoo/redteam/public/build.ts --out promptfoo/out/public
 *
 * Writes tests.yaml (the cases, for public.yaml) and build.json (config, sources with pinned and read revisions, pool sizes). A source that
 * cannot be read is listed in build.json as failed and the night goes on with the others; with no source at all the benign READMEs still run.
 * Env: REDTEAM_SEED, REDTEAM_PUBLIC_PER_GROUP (25), REDTEAM_PUBLIC_PER_GROUP_BLOCKED (15), REDTEAM_PUBLIC_MODEL_CASES (40),
 *      REDTEAM_PUBLIC_BENIGN (60), REDTEAM_PUBLIC_FOREIGN (20), REDTEAM_PUBLIC_ENCODED (10 per encoding).
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { stringify } from "yaml";
import { buildCases, configFrom, sampleRows, type PublicCase, type PublicConfig } from "./cases.js";
import { SOURCES, readAll, realDeps, type FetchDeps, type SourceReport, type SourceSpec } from "./sources.js";
import type { BuildInfo } from "./aggregate.js";

export const ASSERTIONS = ["harness"] as const;

/** promptfoo renders the string vars as templates: a dataset text with `{{ }}`, `{% %}` or `{# #}` (template injections are a classic attack) is wrapped in a raw block, which renders to the text itself. */
export const rawVar = (v: unknown): unknown => (typeof v === "string" && /\{\{|\{%|\{#/.test(v) ? `{% raw %}${v}{% endraw %}` : v);

/** One case as a promptfoo test. The metadata repeats the grouping so the raw results are readable without the report. */
export function toTest(c: PublicCase): { description: string; vars: Record<string, unknown>; assert: { type: "javascript"; value: string }[]; metadata: Record<string, unknown> } {
  return {
    description: `PUBLIC ${c.stage}${c.encoding ? "-" + c.encoding : ""} ${c.dataset} ${c.language}`,
    vars: { kind: "public", ...Object.fromEntries(Object.entries(c).map(([k, v]) => [k, rawVar(v)])) },
    assert: ASSERTIONS.map((fn) => ({ type: "javascript" as const, value: `file://public/public-assertions.js:${fn}` })),
    metadata: { stage: c.stage, dataset: c.dataset, language: c.language, ...(c.encoding ? { encoding: c.encoding } : {}) },
  };
}

export interface Built {
  tests: ReturnType<typeof toTest>[];
  info: BuildInfo;
}

export async function build(cfg: PublicConfig, deps: FetchDeps, specs: SourceSpec[] = SOURCES, read: typeof readAll = readAll): Promise<Built> {
  const { rows, reports } = await read(specs, cfg.seed, deps);
  const sample = sampleRows(rows, cfg);
  const { cases, tooShort } = buildCases(sample, cfg);
  const sources: SourceReport[] = reports;
  return { tests: cases.map(toTest), info: { config: cfg, sources, pools: sample.pools, dropped: sample.dropped, tooShort, cases: cases.length } };
}

async function main(): Promise<void> {
  const argv = process.argv.slice(2);
  const out = resolve(argv.includes("--out") ? argv[argv.indexOf("--out") + 1]! : "promptfoo/out/public");
  const cfg = configFrom(process.env);
  // PUBLIC_ROWS_CACHE=file.json (local development only): the rows fetched once are reused, the network is not asked again
  const cache = process.env.PUBLIC_ROWS_CACHE;
  const cached: typeof readAll = async (specs, seed, deps) => {
    if (cache && existsSync(cache)) return JSON.parse(readFileSync(cache, "utf8")) as Awaited<ReturnType<typeof readAll>>;
    const r = await readAll(specs, seed, deps);
    if (cache) writeFileSync(cache, JSON.stringify(r));
    return r;
  };
  const built = await build(cfg, realDeps, SOURCES, cached);
  mkdirSync(out, { recursive: true });
  writeFileSync(resolve(out, "tests.yaml"), "# PUBLIC dataset tests of the nightly run (generated by promptfoo/redteam/public/build.ts, never committed)\n" + stringify(built.tests, { lineWidth: 0 }));
  writeFileSync(resolve(out, "build.json"), JSON.stringify(built.info, null, 2) + "\n");
  for (const s of built.info.sources) console.error(`public source ${s.key}: ${s.status}, ${s.rows} rows${s.error ? ", " + s.error : ""}${s.drifted ? ", REVISION DRIFTED" : ""}`);
  console.error(`public part: seed ${cfg.seed}, ${built.info.cases} cases written to ${out}`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch((err: unknown) => {
    console.error(err instanceof Error ? err.message : err);
    process.exit(1);
  });
}
