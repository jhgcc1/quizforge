/**
 * Step after curate.ts in the nightly run: makes the generated tests fit the nightly set.
 *   - vars.layout: where the attack goes (document paragraph, one section of a very long document, or the topic field);
 *   - metadata.group: the kind of threat (placement, answer-key, ...), for the report;
 *   - the assertions are the nightly ones (nightly-assertions.js: a refused topic is a safe outcome too).
 *
 *   tsx promptfoo/redteam/nightly-tests.ts promptfoo/out/nightly/tests.yaml
 */
import { readFileSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";
import { parse, stringify } from "yaml";
import type { RedteamTest } from "./curate.js";
import { NIGHTLY_BY_ID } from "./intents-nightly.js";

export const NIGHTLY_ASSERTIONS = ["canaryAbsent", "noPromptLeak", "safeOutcome", "expectedStage"] as const;

export type NightlyTest = Omit<RedteamTest, "vars" | "metadata"> & {
  vars: RedteamTest["vars"] & { layout: "document" | "long" | "topic" };
  metadata: RedteamTest["metadata"] & { group: string };
};

export function toNightlyTest(t: RedteamTest): NightlyTest {
  const x = NIGHTLY_BY_ID.get(t.metadata.intent);
  return {
    ...t,
    vars: { ...t.vars, layout: x?.layout ?? "document" },
    assert: NIGHTLY_ASSERTIONS.map((fn) => ({ type: "javascript" as const, value: `file://nightly-assertions.js:${fn}` })),
    metadata: { ...t.metadata, group: x?.group ?? "base" },
  };
}

function main(): void {
  const file = process.argv[2];
  if (!file) throw new Error("usage: nightly-tests.ts <tests.yaml>");
  const tests = parse(readFileSync(file, "utf8")) as RedteamTest[];
  writeFileSync(file, "# NIGHTLY red team tests (generated by scripts/promptfoo.sh redteam-nightly, never committed)\n" + stringify(tests.map(toNightlyTest), { lineWidth: 0 }));
  console.log(`${tests.length} nightly tests written to ${file}`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();
