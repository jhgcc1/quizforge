/**
 * The ENCODING strategies (base64, rot13, leetspeak) in the nightly run. promptfoo applies them to the intent texts exactly as it does for
 * the frozen sample (redteam.config.yaml), but to a SUBSET of the fresh texts: REDTEAM_ENCODED_PER_INTENT texts per intent (default 3), each
 * encoded three ways. An encoded text would hide the markup a placement is about, so these cases always use the plain document layout.
 * They should stop at the input guard (hidden or encoded text blocks); one that reaches the model is counted and reported (an alert, never a failure).
 *
 *   subset  tsx promptfoo/redteam/nightly-encoded.ts subset --in promptfoo/out/nightly --out promptfoo/out/nightly/encoded --per-intent 3 --seed 20261015
 *           (writes intents.json + intents.meta.json of the subset; the script then runs `promptfoo redteam generate` on it with redteam.nightly-encoded.yaml)
 *   tests   tsx promptfoo/redteam/nightly-encoded.ts tests --generated promptfoo/out/nightly/encoded/generated.yaml --meta promptfoo/out/nightly/encoded/intents.meta.json --tests promptfoo/out/nightly/tests.yaml
 *           (appends the encoded cases to the nightly tests)
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { parse, stringify } from "yaml";
import { writeIntents } from "./build-intents.js";
import { toRedteamTests, type GeneratedTest, type RedteamTest } from "./curate.js";
import { seededRandom, type IntentMeta } from "./intents.js";
import { toNightlyTest, type NightlyTest } from "./nightly-tests.js";

export const ENCODING_STRATEGIES = ["base64", "rot13", "leetspeak"] as const;

/** `perIntent` texts of every intent, picked with the seed (the same every run for one seed). */
export function subsetOf(metas: IntentMeta[], perIntent: number, seed: number): IntentMeta[] {
  const rnd = seededRandom(seed);
  const byIntent = new Map<string, IntentMeta[]>();
  for (const m of metas) (byIntent.get(m.intent) ?? byIntent.set(m.intent, []).get(m.intent)!).push(m);
  const out: IntentMeta[] = [];
  for (const [, list] of [...byIntent].sort(([a], [b]) => a.localeCompare(b))) {
    const pool = [...list];
    for (let i = pool.length - 1; i > 0; i--) {
      const j = Math.floor(rnd() * (i + 1));
      [pool[i], pool[j]] = [pool[j]!, pool[i]!];
    }
    out.push(...pool.slice(0, perIntent));
  }
  return out;
}

/** The encoded cases as nightly tests: only the encoding strategies (the plain copy promptfoo keeps is already in the main run), layout "document". */
export function encodedTests(generated: GeneratedTest[], metas: IntentMeta[]): NightlyTest[] {
  return toRedteamTests(generated, metas)
    .filter((t: RedteamTest) => (ENCODING_STRATEGIES as readonly string[]).includes(t.metadata.strategy))
    .map((t) => {
      const n = toNightlyTest(t);
      return { ...n, vars: { ...n.vars, layout: "document" as const }, metadata: { ...n.metadata, group: "encoded" } };
    });
}

function main(): void {
  const argv = process.argv.slice(2);
  const mode = argv[0];
  const get = (n: string, d?: string): string => {
    const v = argv.includes(n) ? argv[argv.indexOf(n) + 1] : d;
    if (v === undefined) throw new Error(`missing ${n}`);
    return v;
  };
  if (mode === "subset") {
    const perIntent = Number(get("--per-intent", "3"));
    if (!Number.isInteger(perIntent) || perIntent < 0) throw new Error("--per-intent must be a non-negative integer");
    const metas = JSON.parse(readFileSync(resolve(get("--in"), "intents.meta.json"), "utf8")) as IntentMeta[];
    const subset = subsetOf(metas, perIntent, Number(get("--seed", "1")));
    writeIntents(resolve(get("--out")), subset);
    console.log(`${subset.length} texts (${perIntent} per intent) written for the encodings`);
  } else if (mode === "tests") {
    const generated = (parse(readFileSync(get("--generated"), "utf8")) as { tests: GeneratedTest[] }).tests;
    const metas = JSON.parse(readFileSync(get("--meta"), "utf8")) as IntentMeta[];
    const file = get("--tests");
    const main = parse(readFileSync(file, "utf8")) as unknown[];
    const extra = encodedTests(generated, metas);
    writeFileSync(file, "# NIGHTLY red team tests (generated by scripts/promptfoo.sh redteam-nightly, never committed)\n" + stringify([...main, ...extra], { lineWidth: 0 }));
    console.log(`${extra.length} encoded cases appended to ${file}`);
  } else throw new Error("usage: nightly-encoded.ts subset|tests ...");
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();
